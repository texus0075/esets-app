export const ALL_DISTRICTS = LOCATIONS.flatMap(loc => 
  loc.districts.map(d => ({ district: d, state: loc.state }))
);

export const getAllStates = () => LOCATIONS.map(l => l.state);

export const getDistrictsForState = (stateName) => {
  if (!stateName) return [];
  const found = LOCATIONS.find(l => l.state.toLowerCase() === stateName.toLowerCase());
  return found ? found.districts : [];
};

export const findStateForDistrict = (districtName) => {
  if (!districtName) return "";
  for (const loc of LOCATIONS) {
    if (loc.districts.some(d => d.toLowerCase() === districtName.toLowerCase())) {
      return loc.state;
    }
  }
  return "";
};
